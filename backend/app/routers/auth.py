@router.post("/register", response_model=schemas.UserOut)
def register(user_in: schemas.UserCreate, db: Session = Depends(get_db)):
    existing = db.query(models.User).filter(models.User.email == user_in.email).first()
    if existing:
        raise HTTPException(status_code=400, detail="User with this email already exists")
    
    user = models.User(
        email=user_in.email,
        full_name=user_in.full_name,
        hashed_password=hash_password(user_in.password),
        role=user_in.role or "RESEARCHER",
        organization=user_in.organization or "National Land Policy Institute"
    )
    db.add(user)
    db.commit()
    db.refresh(user)
    return user

@router.get("/me", response_model=schemas.UserOut)
def get_me(current_user: models.User = Depends(get_current_user)):
    return current_user

@router.post("/demo-switch", response_model=schemas.Token)
def switch_demo_role(role: str, db: Session = Depends(get_db)):
    """Allows rapid switching between roles in Demo Mode."""
    role = role.upper()
    if role not in ["PUBLIC", "RESEARCHER", "POLICYMAKER", "ADMIN"]:
        raise HTTPException(status_code=400, detail="Invalid role")
    
    user = db.query(models.User).filter(models.User.role == role).first()
    if not user:
        # Fallback to any user
        user = db.query(models.User).first()
        if not user:
            raise HTTPException(status_code=404, detail="No users seeded")
            
    access_token = create_access_token(data={"sub": user.email, "role": user.role})
    return {
        "access_token": access_token,
        "token_type": "bearer",
        "user": {
            "id": user.id,
            "email": user.email,
            "full_name": user.full_name,
            "role": user.role,
            "organization": user.organization
        }
    }
